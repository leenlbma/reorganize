#!/usr/bin/env python3
"""Generate the editable diagrams for Reorganize, first season.

Only Python's standard library is required. Text remains SVG text; no raster
assets, embedded fonts, external resources, or JavaScript are included.
"""

from html import escape
from pathlib import Path


HERE = Path(__file__).resolve().parents[2] / 'images'
C = {
    "bg": "#F8F7F3", "ink": "#203632", "muted": "#586761",
    "line": "#7A8982", "border": "#D7DED7", "white": "#FFFFFF",
    "teal": "#E3EFEB", "teal_ink": "#245E50", "blue": "#E6EDF5",
    "blue_ink": "#365B79", "amber": "#F5EDD9", "amber_ink": "#76591D",
    "rose": "#F2E6E1", "rose_ink": "#815144",
}


class Diagram:
    def __init__(self, number, title, subtitle, desc):
        self.number, self.title, self.desc = number, title, desc
        self.parts = [f'''<svg xmlns="http://www.w3.org/2000/svg" width="1000" height="700" viewBox="0 0 1000 700" role="img" aria-labelledby="title desc">
<title id="title">{escape(title)}</title>
<desc id="desc">{escape(desc)}</desc>
<defs>
  <marker id="arrow" markerWidth="10" markerHeight="10" refX="8" refY="5" orient="auto" markerUnits="userSpaceOnUse"><path d="M1 1 L9 5 L1 9" fill="none" stroke="{C['line']}" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round"/></marker>
</defs>
<style>text {{ font-family: "PingFang SC", "Hiragino Sans GB", "Microsoft YaHei", "Noto Sans CJK SC", sans-serif; }} .connector {{ fill:none; stroke:{C['line']}; stroke-width:2; stroke-linecap:round; stroke-linejoin:round; }} </style>
<rect width="1000" height="700" rx="24" fill="{C['bg']}"/>
<rect x="1" y="1" width="998" height="698" rx="23" fill="none" stroke="{C['border']}"/>
''']
        self.text(50, 57, f"{number:02d}", 22, C["teal_ink"], 600, "start")
        self.text(98, 59, title, 34, C["ink"], 600, "start", (95, 15, 850, 62))
        self.text(50, 107, subtitle, 23, C["muted"], 400, "start", (46, 77, 905, 40))
        self.parts.append(f'<path d="M50 132 H950" stroke="{C["border"]}"/>')

    def text(self, x, y, content, size=24, color=None, weight=400, anchor="middle", region=None):
        attrs = f' data-region="{",".join(str(v) for v in region)}"' if region else ""
        self.parts.append(f'<text x="{x}" y="{y}" fill="{color or C["ink"]}" font-size="{size}" font-weight="{weight}" text-anchor="{anchor}"{attrs}>{escape(content)}</text>')

    def box(self, x, y, w, h, title, lines=(), fill="white", title_size=27):
        self.parts.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="16" fill="{C[fill]}" stroke="{C["border"]}"/>')
        line_count = len(lines)
        total = 34 + (line_count * 32 if line_count else 0)
        start = y + (h - total) / 2 + 27
        self.text(x + w / 2, start, title, title_size, C["ink"], 600, region=(x + 14, y + 6, w - 28, h - 12))
        for i, line in enumerate(lines):
            self.text(x + w / 2, start + 34 + i * 32, line, 23, C["muted"], region=(x + 14, y + 6, w - 28, h - 12))

    def line(self, points, arrow=True, dashed=False):
        coords = " ".join(("M" if i == 0 else "L") + f"{x} {y}" for i, (x, y) in enumerate(points))
        end = ' marker-end="url(#arrow)"' if arrow else ""
        dash = ' stroke-dasharray="7 6"' if dashed else ""
        self.parts.append(f'<path class="connector" d="{coords}"{end}{dash}/>')

    def note(self, y, line1, line2=None):
        self.text(500, y, line1, 23, C["muted"], region=(45, y - 26, 910, 36))
        if line2:
            self.text(500, y + 32, line2, 23, C["muted"], region=(45, y + 6, 910, 36))

    def save(self):
        self.parts.append("</svg>\n")
        (HERE / f"s01-{self.number:02d}.svg").write_text("\n".join(self.parts), encoding="utf-8")


